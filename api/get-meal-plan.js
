import { GoogleGenerativeAI } from "@google/generative-ai";

export default async function handler(req, res) {
  // 1. Only allow POST requests
  if (req.method !== 'POST') {
    return res.status(405).json({ error: 'Method not allowed' });
  }

  // 2. Grab the API key you saved in the Vercel Dashboard
  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey) {
    return res.status(500).json({ error: 'API key not configured on Vercel' });
  }

  try {
    const body = req.body;
    let finalPrompt = "";

    // 3. Handle both data formats gracefully
    if (body.messages && Array.isArray(body.messages)) {
      // If your frontend uses the structured 'messages' array format from your old code
      finalPrompt = body.messages.map(m => m.content).join('\n');
    } else if (body.goals) {
      // If your frontend sends a simple 'goals' string
      finalPrompt = `Act as an expert fitness nutritionist. Create a practical meal plan for someone with these specific goals: ${body.goals}. Break it down clearly into Breakfast, Lunch, and Dinner.`;
    } else {
      return res.status(400).json({ error: 'Invalid request payload' });
    }

    // 4. Initialize Gemini correctly using the formal SDK library
    const genAI = new GoogleGenerativeAI(apiKey);
    // Using the stable flash model instead of preview endpoints
    const model = genAI.getGenerativeModel({ model: "gemini-1.5-flash" });

    const result = await model.generateContent(finalPrompt);
    const responseData = await result.response;
    const textOutput = responseData.text();

    // 5. Return the exact same JSON structure your frontend expects (Anthropic style format)
    return res.status(200).json({
      content: [
        { type: 'text', text: textOutput }
      ]
    });

  } catch (error) {
    console.error('Function error:', error);
    return res.status(500).json({ error: error.message || 'Internal server error' });
  }
}
